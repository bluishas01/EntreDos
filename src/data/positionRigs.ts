export interface FigurePose {
  hip: [number, number];
  torsoDeg: number;
  headDeg: number;
  chestSide: 1 | -1;
  farThighDeg: number;
  farKneeDeg: number;
  farFootDeg: number;
  nearThighDeg: number;
  nearKneeDeg: number;
  nearFootDeg: number;
  farArmDeg: number;
  farElbowDeg: number;
  nearArmDeg: number;
  nearElbowDeg: number;
  /** Optional subtle torso arch bend along chestSide (+ arches chest out, - rounds back) */
  arch?: number;
}

export interface MotionSpec {
  target: 'him' | 'her' | 'both';
  dx: number;
  dy: number;
  rotDeg?: number;
  /** Secondary subtle reaction on the other partner */
  counterDx?: number;
  counterDy?: number;
  arrow: {
    x: number;
    y: number;
    angle: number;
    mode?: 'linear' | 'circle';
  };
}

export interface PositionRig {
  prop: PoseSceneProp;
  drawOrder: 'her-first' | 'him-first';
  him: FigurePose;
  her: FigurePose;
  motion: MotionSpec;
}

